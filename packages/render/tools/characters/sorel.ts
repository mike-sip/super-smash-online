// --- Aides d'écriture --------------------------------------------------------------------------

const key = (at: number | string, pose: Posture, ease?: Ease): Key =>
  ease === undefined ? { at, pose } : { at, pose, ease };

/**
 * Coup type : anticipation, frappe en place à la première frame active, tenue jusqu'à la
 * dernière, suivi, puis retour. `ret` : pose de retour (garde au sol, garde en l'air).
 */
function strike(
  name: string,
  move: number,
  p: {
    wind: Posture;
    hit: Posture;
    hold?: Posture;
    follow?: Posture;
    ret?: Posture;
    air?: boolean;
    windAt?: string;
    vel?: readonly [number, number];
  },
): Clip {
  const air = p.air === true;
  const keys: Key[] = [
    key(p.windAt ?? 's*0.55', p.wind, 'inOut'),
    key('s', p.hit, 'snap'),
    key('e', p.hold ?? {}, 'linear'),
    key('e+4', p.follow ?? {}, 'out'),
    key('t', p.ret ?? (air ? AIR : GUARD), 'settle'),
  ];
  return {
    name,
    action: A_ATTACK,
    move,
    keys,
    ...(air ? { air: true, from: AIR } : {}),
    ...(p.vel === undefined ? {} : { vel: p.vel }),
  };
}

/** Action à durée connue, écrite clé par clé. */
const timed = (name: string, action: number, keys: Key[], extra: Partial<Clip> = {}): Clip => ({
  name,
  action,
  keys,
  ...extra,
});

/** Boucle de période `loop` frames. */
const loop = (
  name: string,
  action: number,
  period: number,
  keys: Key[],
  extra: Partial<Clip> = {},
): Clip => ({
  name,
  action,
  loop: period,
  keys,
  ...extra,
});

