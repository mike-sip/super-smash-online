/** Smash en charge : la pose d'anticipation tremble d'énergie contenue, le vent monte. */
function charge(name: string, move: number, base: Posture): Clip {
  return loop(
    `${name}_charge`,
    A_ATTACK,
    12,
    [
      key(0, base),
      key(3, {
        ...base,
        torso: (base.torso ?? 0) + 0.04,
        armF: (base.armF ?? 0) + 0.05,
        offsetX: -0.006,
      }),
      key(6, { ...base, torso: (base.torso ?? 0) - 0.02 }),
      key(9, { ...base, armB: (base.armB ?? 0) - 0.05, offsetX: 0.006 }),
    ],
    { move },
  );
}

